// Package db 提供数据库连接池与事务管理器。
//
// 本包只做平台级基础设施：连接池参数、启动自检、事务边界、死锁重试与错误映射。
// 不包含任何业务规则，也不认识表结构——写 SQL 是各模块 infra 层的职责。
//
// 事务语义固定如下（ADR-0003）：
//
//   - TransactionManager.Do 在单个事务内执行 fn；fn 返回错误或 panic 时整体回滚。
//   - fn 内的唯一合法句柄是传入的 tx。使用连接池上的 *gorm.DB 会跑在事务之外，
//     回滚时留下脏数据。
//   - 死锁（1213）与锁等待超时（1205）会重试整个事务，因此 fn 必须可重入：
//     不得在闭包外累积状态，不得产生 DB 之外的副作用。
//   - 重试耗尽返回 DEPENDENCY_UNAVAILABLE，而不是 CONFLICT。瞬时争用不等于
//     业务前提不成立，客户端应按退避重试。
//
// 事务内禁止调用 Kafka/HTTP/Redis/asynq。Outbox 写入是同库同事务的本地写，
// 不在此限。
