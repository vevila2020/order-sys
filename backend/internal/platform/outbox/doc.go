// Package outbox 实现事务 Outbox 的写入端。
//
// 为什么需要它：事务内直接发 Kafka 会出现"事件已发、事务回滚"的幽灵事件，
// 反过来"事务已提交、事件发送失败"则永久丢事件。Outbox 把事件与业务数据写在
// 同一个本地事务里，进程崩溃也不会让两者分裂（ADR-0003 第 6 节）。
//
// M1 只写入 status='PENDING' 的记录；真正的发布由 worker 的 relay 在事务提交后
// 完成（M3）。因此本包不关心投递、重试或顺序，只保证"写入的原子性"与
// "信封字段完整"。
//
// 事务内不产生任何网络调用：INSERT 是本地写，符合 ADR-0003 对持锁期间外部 I/O
// 的禁令。
package outbox
