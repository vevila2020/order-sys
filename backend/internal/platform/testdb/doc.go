//go:build integration

// Package testdb 为集成测试提供一次性的真实 MySQL 实例与迁移执行工具。
//
// 本包整体受 build tag integration 约束（见 testdb.go），默认的 go test 不会
// 编译它，因此没有 Docker 的开发机仍能跑完整的单元测试。
//
// 为什么用容器而不是远程开发库：集成测试会执行迁移、建表、写数据、制造死锁。
// 指向共享库会污染他人数据、让测试相互干扰，并且让"同一个测试第二次运行"不再
// 可复现。每个测试拿到自己的库，结束时丢弃。
//
// 为什么是包级而不是每个测试各写一份：T04、T09–T15、T17 都需要同样的启动、
// 等待就绪、跑迁移、清理。重复实现会让"某个测试忘了关容器"变成进程泄漏。
